class Explicit {
    public static void main(String[] args) {
        double dou = 10.2345;
        int val = (int)dou;
        System.out.println(dou);
        System.out.println(val);

        //Type casting using Explicit 

        int val2 =50;
        char ch =(char)val2;
        float val3= 3.14f;
        byte by =(byte)val3;
        System.out.println(val2);
        System.out.println(ch);
        System.out.println(val3);
        System.out.println(by);


    }
}
